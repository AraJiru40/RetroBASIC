import Foundation

enum MIDIFixture {
    static func make() -> Data {
        let tempoTrack = track([
            0x00, 0xFF, 0x03, 0x05, 0x54, 0x65, 0x6D, 0x70, 0x6F,
            0x00, 0xFF, 0x51, 0x03, 0x07, 0xA1, 0x20,
            0x83, 0x60, 0xFF, 0x51, 0x03, 0x0F, 0x42, 0x40,
            0x00, 0xFF, 0x2F, 0x00,
        ])
        let leadTrack = track([
            0x00, 0xFF, 0x03, 0x04, 0x4C, 0x65, 0x61, 0x64,
            0x00, 0xC0, 0x00,
            0x00, 0x90, 0x3C, 0x64,
            0x00, 0x90, 0x40, 0x50,
            0x83, 0x60, 0x80, 0x3C, 0x00,
            0x00, 0x80, 0x40, 0x00,
            0x00, 0x90, 0x43, 0x5A,
            0x81, 0x70, 0x43, 0x00,
            0x00, 0xFF, 0x2F, 0x00,
        ])
        let drumTrack = track([
            0x00, 0xFF, 0x03, 0x05, 0x44, 0x72, 0x75, 0x6D, 0x73,
            0x00, 0x99, 0x24, 0x70,
            0x78, 0x89, 0x24, 0x00,
            0x78, 0x99, 0x26, 0x64,
            0x78, 0x89, 0x26, 0x00,
            0x00, 0xFF, 0x2F, 0x00,
        ])

        var data = Data("MThd".utf8)
        appendUInt32(6, to: &data)
        appendUInt16(1, to: &data)
        appendUInt16(3, to: &data)
        appendUInt16(480, to: &data)
        data.append(tempoTrack)
        data.append(leadTrack)
        data.append(drumTrack)
        return data
    }

    private static func track(_ bytes: [UInt8]) -> Data {
        var data = Data("MTrk".utf8)
        appendUInt32(UInt32(bytes.count), to: &data)
        data.append(contentsOf: bytes)
        return data
    }

    private static func appendUInt16(_ value: UInt16, to data: inout Data) {
        data.append(UInt8((value >> 8) & 0xFF))
        data.append(UInt8(value & 0xFF))
    }

    private static func appendUInt32(_ value: UInt32, to data: inout Data) {
        data.append(UInt8((value >> 24) & 0xFF))
        data.append(UInt8((value >> 16) & 0xFF))
        data.append(UInt8((value >> 8) & 0xFF))
        data.append(UInt8(value & 0xFF))
    }
}
