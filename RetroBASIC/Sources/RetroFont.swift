/// An 8x8 dot-matrix font in the spirit of the Japanese 8-bit machines of the
/// early 1980s (N88-BASIC / PC-8801).
///
/// The cell is 8x8 dots and glyphs are drawn 6 dots wide (7 for katakana),
/// leaving the remaining columns as the inter-character gap. 80 columns of
/// 8-dot cells span exactly 640 dots and 25 rows span exactly 200 -- the same
/// pixel space as the graphics plane, which is what makes text and graphics
/// line up on a real machine.
///
/// ASCII glyphs are written as dot art. Katakana and GRPH glyphs use packed
/// character-ROM rows so their complete 8-dot shapes are preserved.
enum RetroFont {
    static let cellWidth = 8
    static let cellHeight = 8

    static let blank = [UInt8](repeating: 0, count: cellHeight)

    /// Eight rows of dots, top first. Bit 7 is the leftmost dot of the cell.
    static func glyph(for scalar: Unicode.Scalar) -> [UInt8]? {
        glyph(forByte: RetroCharset.byte(for: Character(scalar)))
    }

    static func glyph(forByte byte: UInt8?) -> [UInt8]? {
        guard let byte else { return nil }
        switch byte {
        case 0x20...0x7E: return ascii[Int(byte - 0x20)]
        case 0x80...0x9F: return graph80[Int(byte - 0x80)]
        case 0xA1...0xDF: return kana[Int(byte - 0xA1)]
        case 0xE0...0xF7: return graphE0[Int(byte - 0xE0)]
        default: return nil
        }
    }

    /// Dot art -> packed rows. Short rows are padded on the right and missing
    /// rows at the bottom are blank, so trailing empty lines can be left out.
    static func pack(_ art: String) -> [UInt8] {
        var rows: [UInt8] = []
        for line in art.split(separator: "\n", omittingEmptySubsequences: false) {
            var bits: UInt8 = 0
            for (i, c) in line.enumerated() where c == "#" && i < cellWidth {
                bits |= UInt8(0x80) >> UInt8(i)
            }
            rows.append(bits)
        }
        while rows.count < cellHeight { rows.append(0) }
        return Array(rows.prefix(cellHeight))
    }

